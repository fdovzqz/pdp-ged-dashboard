// Calcular totales mensuales
const calculateMonthlyTotals = (data: Record<string, number>, year: number): number[] => {
  const monthlyTotals = Array(12).fill(0);
  
  Object.entries(data).forEach(([dateStr, value]) => {
    const date = new Date(dateStr);
    if (date.getFullYear() === year) {
      const month = date.getMonth();
      monthlyTotals[month] += value;
    }
  });
  
  return monthlyTotals;
};

// Totales mensuales
const monthlyTotals2024 = calculateMonthlyTotals(dailyData2024Raw, 2024);
const monthlyTotals2025 = calculateMonthlyTotals(dailyData2025Raw, 2025);

// Datos mensuales para comparación
export const monthlyComparisonData: MonthlyData[] = MONTH_NAMES.map((name, index) => {
  const val2024 = monthlyTotals2024[index];
  const val2025 = monthlyTotals2025[index];
  const difference = val2025 - val2024;
  const growthRate = val2024 > 0 ? ((val2025 - val2024) / val2024) * 100 : 0;
  
  return {
    month: index + 1,
    monthName: name,
    '2024': val2024,
    '2025': val2025,
    difference,
    growthRate,
  };
});

